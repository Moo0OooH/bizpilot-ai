/**
 * Produces protected-dashboard copy only. `business.preferred_language` must
 * continue to drive public quote pages, persisted customer content, and AI.
 */
export function getDashboardInterfaceLegacyCopy(
  language: unknown,
): DashboardInterfaceLegacyCopy {
  const resolvedLanguage = readDashboardInterfaceLanguage(language);
  const source = getBizPilotCopy(
    resolvedLanguage === "fr-CA" ? "fr-CA" : "en",
  );
  const translations =
    resolvedLanguage === "fa" ||
    resolvedLanguage === "ar" ||
    resolvedLanguage === "es"
      ? legacyStaticTranslations[resolvedLanguage]
      : undefined;

  const dashboard = translations
    ? translateStaticValue(source.dashboard, translations, ["dashboard"])
    : source.dashboard;

  return {
    dashboard: localizeDynamicDashboardCopy(resolvedLanguage, dashboard),
    demo: translations
      ? translateStaticValue(source.demo, translations, ["demo"])
      : source.demo,
    missingInfoLabels: translations
      ? translateStaticValue(source.missingInfoLabels, translations, [
          "missingInfoLabels",
        ])
      : source.missingInfoLabels,
  };
}

/**
 * Locale-aware presentation with Latin digits. This is for dashboard display
 * only and is deliberately distinct from business/customer language.
 */
export function getDashboardInterfaceFormattingLocale(language: unknown): string {
  switch (readDashboardInterfaceLanguage(language)) {
    case "ar":
      return "ar-u-nu-latn";
    case "es":
      return "es-u-nu-latn";
    case "fa":
      return "fa-u-nu-latn";
    case "fr-CA":
      return "fr-CA-u-nu-latn";
    default:
      return "en-CA-u-nu-latn";
  }
}
