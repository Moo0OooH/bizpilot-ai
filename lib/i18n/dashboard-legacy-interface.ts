function isProtectedDashboardDataValue(
  path: readonly string[],
  value: string,
): boolean {
  const joinedPath = path.join(".");

  return (
    value === "" ||
    value.startsWith("/") ||
    joinedPath === "dashboard.admin.locale" ||
    joinedPath === "dashboard.businessProfile.serviceAreasPlaceholder" ||
    joinedPath === "dashboard.overview.featuredFallbackArea" ||
    joinedPath === "dashboard.overview.featuredFallbackCustomer" ||
    /^dashboard\.configuration\.fields\.placeholders\.[^.]+\.(?:fieldKey|helper|label|options|preview)$/u.test(
      joinedPath,
    ) ||
    /^dashboard\.configuration\.sourceLinks\.presets\.\d+\.(?:key|medium)$/u.test(
      joinedPath,
    ) ||
    /^dashboard\.configuration\.faq\.(?:examples\.\d+|placeholder)$/u.test(
      joinedPath,
    ) ||
    /^dashboard\.configuration\.sourceLinks\.(?:campaignPlaceholder|customPlaceholder)$/u.test(
      joinedPath,
    ) ||
    /^demo\.(?:aiSummary|detailFour|detailOne|detailThree|detailTwo|featuredLeadTitle|followUpDraft|missingInfo|replyDraft)$/u.test(
      joinedPath,
    ) ||
    /^demo\.sampleAreas\.\d+$/u.test(joinedPath) ||
    /^demo\.sampleLeads\.\d+\.(?:area|customer|detail|followUpDraft|replyDraft|tone)$/u.test(
      joinedPath,
    )
  );
}

function translateStaticValue<T>(
  value: T,
  translations: StaticTranslationMap,
  path: readonly string[] = [],
): T {
  if (typeof value === "string") {
    if (isProtectedDashboardDataValue(path, value)) return value;
    return (translations[value] ?? value) as T;
  }

  if (Array.isArray(value)) {
    return value.map((entry, index) =>
      translateStaticValue(entry, translations, [...path, String(index)]),
    ) as T;
  }

  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value).map(([key, entry]) => [
        key,
        translateStaticValue(entry, translations, [...path, key]),
      ]),
    ) as T;
  }

  return value;
}

